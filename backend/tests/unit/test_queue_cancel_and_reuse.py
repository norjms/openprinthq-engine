"""#55: cancel a queued job with a reason, and reuse a library file instead of storing a copy."""

from __future__ import annotations

import io

from sqlalchemy import func, select

from backend.app.models.library import LibraryFile
from backend.app.models.print_queue import PrintQueueItem


class TestCancelWithReason:
    async def test_reason_and_who_are_kept(self, async_client, db_session):
        item = PrintQueueItem(status="pending", position=1)
        db_session.add(item)
        await db_session.commit()
        r = await async_client.post(f"/api/v1/queue/{item.id}/cancel", json={"reason": " wrong colour ", "by": "james"})
        assert r.status_code == 200, r.text
        assert r.json()["cancel_reason"] == "wrong colour" and r.json()["cancelled_by"] == "james"
        got = (await async_client.get(f"/api/v1/queue/{item.id}")).json()
        assert got["status"] == "cancelled"
        assert got["cancel_reason"] == "wrong colour" and got["cancelled_by"] == "james"

    async def test_no_body_still_cancels(self, async_client, db_session):
        item = PrintQueueItem(status="pending", position=1)
        db_session.add(item)
        await db_session.commit()
        r = await async_client.post(f"/api/v1/queue/{item.id}/cancel")
        assert r.status_code == 200, r.text
        assert r.json()["cancel_reason"] is None
        assert (await async_client.get(f"/api/v1/queue/{item.id}")).json()["status"] == "cancelled"

    async def test_started_items_are_refused(self, async_client, db_session):
        item = PrintQueueItem(status="printing", position=1)
        db_session.add(item)
        await db_session.commit()
        r = await async_client.post(f"/api/v1/queue/{item.id}/cancel", json={"reason": "x"})
        assert r.status_code == 400

    async def test_reason_length_is_checked(self, async_client, db_session):
        item = PrintQueueItem(status="pending", position=1)
        db_session.add(item)
        await db_session.commit()
        r = await async_client.post(f"/api/v1/queue/{item.id}/cancel", json={"reason": "x" * 501})
        assert r.status_code == 422


async def _upload(client, data: bytes, name: str, **params):
    files = {"file": (name, io.BytesIO(data), "application/octet-stream")}
    return await client.post("/api/v1/library/files", files=files, params=params)


class TestUploadReuse:
    async def test_reuse_answers_the_stored_file(self, async_client, db_session):
        data = b"; generated by test\nG28\nG1 X10\n"
        first = await _upload(async_client, data, "part.gcode")
        assert first.status_code == 200, first.text
        assert first.json()["reused"] is False
        again = await _upload(async_client, data, "part-copy.gcode", reuse_duplicate="true")
        assert again.status_code == 200, again.text
        body = again.json()
        assert (
            body["reused"] is True and body["id"] == first.json()["id"] and body["duplicate_of"] == first.json()["id"]
        )
        count = await db_session.scalar(select(func.count()).select_from(LibraryFile))
        assert count == 1

    async def test_default_still_stores_a_copy(self, async_client, db_session):
        data = b"; another\nG28\n"
        first = await _upload(async_client, data, "a.gcode")
        second = await _upload(async_client, data, "b.gcode")
        assert second.json()["reused"] is False
        assert second.json()["duplicate_of"] == first.json()["id"]
        assert second.json()["id"] != first.json()["id"]

    async def test_new_content_is_stored_even_with_reuse(self, async_client, db_session):
        r = await _upload(async_client, b"; unique\nG1 Y5\n", "u.gcode", reuse_duplicate="true")
        assert r.status_code == 200 and r.json()["reused"] is False and r.json()["duplicate_of"] is None
